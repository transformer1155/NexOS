#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generate the two prototype deliverables from prototypes/specs.json.

    python3 prototypes/gen.py

  -> prototypes/html/apps.js          (data for the clickable HTML prototype)
  -> prototypes/mex/<App>/Program.cs (18 standalone .mex C# skeletons)

specs.json is the single source of truth.  The generated files are ordinary
readable source: feel free to edit them directly, but re-running this script
will overwrite them.
"""
import io
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = os.path.join(HERE, "specs.json")
HTML_DIR = os.path.join(HERE, "html")
MEX_DIR = os.path.join(HERE, "mex")

with open(SPEC, "r", encoding="utf-8") as fh:
    SPEC_DATA = json.load(fh)
APPS = SPEC_DATA["apps"]

# Containers that receive clicks in the prototype.
CLICKABLE = {"button", "toggle", "input", "tabs", "list", "grid",
             "canvas", "slider", "progress", "stepper", "toolbar", "panel"}


def ident(s):
    s = re.sub(r"[^A-Za-z0-9_]", "_", str(s))
    if not s or s[0].isdigit():
        s = "c" + s
    return s


def cs(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_cs(app):
    key = app["key"]
    zh = app["zh"]
    title = app["title"]
    status = app["status"]
    w, h, minw, minh = app["win"]
    layout = app["layout"]
    out = []
    A = out.append

    A("// =====================================================================")
    A("//  %s  (%s)  --  STANDALONE .mex INTERACTION PROTOTYPE" % (key, zh))
    A("// ---------------------------------------------------------------------")
    A("//  GENERATED by prototypes/gen.py from prototypes/specs.json.")
    A("//  This is a PROTOTYPE: layout, hit regions and dispatch are in place,")
    A("//  the actual behaviour is marked TODO for you to fill in.")
    A("//")
    A("//  Kind=%d   mex=%s.mex   status=%s" % (app["id"], key, status))
    A("//  Window: %dx%d (min %dx%d) -- note the kernel currently builds" % (w, h, minw, minh))
    A("//  standalone windows at 480x360 (gui_legacy.cpp:8541); change that")
    A("//  default or pass a size before these numbers become authoritative.")
    A("//")
    A("//  CONTRACT (mforms.cpp slot_symbol):")
    A("//    App.Main::Init / Paint(id,w,h) / Click(id,x,y) / Key(id,ch) / Title(id)")
    A("//  Each window owns its own CLR slot; `id` is the opaque window handle")
    A("//  (NEX_APP_HANDLE_BASE + slot), NOT a shared static index.")
    A("//")
    A("//  MiniCLR limits: no System.Collections, no string '+', no static")
    A("//  initialisers, no float/generic/try-catch.  Use U.Cat for strings,")
    A("//  fixed-size arrays + linear search instead of Dictionary, and never")
    A("//  hold a newly allocated object across Paint frames.")
    A("// ---------------------------------------------------------------------")
    A("")
    A("// Event sequence (from specs.json):")
    for ev in app["events"]:
        A("//   - %s" % ev)
    A("// Acceptance points:")
    for ac in app["accept"]:
        A("//   - %s" % ac)
    A("// Right-click menu: %s" % " / ".join(app["menu"]))
    A("// State fields to model: %s" % ", ".join(app["state"]))
    A("// =====================================================================")
    A("")
    A("using NexOS.Forms;")
    A("")
    A("namespace App")
    A("{")
    A("    public static class Main")
    A("    {")
    A("        // MiniCLR does NOT run .cctor: every static starts as null/0.")
    A("        // All state must be created explicitly inside Init().")
    A("        static %sApp app;" % key)
    A("")
    A("        public static void Init()")
    A("        {")
    A("            if (app == null) app = new %sApp();" % key)
    A("        }")
    A("")
    A("        public static int Paint(int id, int w, int h)")
    A("        {")
    A("            Init();")
    A("            app.OnPaint(id, w, h);")
    A("            return 0;")
    A("        }")
    A("")
    A("        public static int Click(int id, int x, int y)")
    A("        {")
    A("            Init();")
    A("            return app.OnClick(id, x, y);")
    A("        }")
    A("")
    A("        public static int Key(int id, int ch)")
    A("        {")
    A("            Init();")
    A("            return app.OnKey(id, ch);")
    A("        }")
    A("")
    A("        public static string Title(int id)")
    A("        {")
    A("            Init();")
    A("            return app.GetTitle(id);")
    A("        }")
    A("    }")
    A("")
    A("    public class %sApp" % key)
    A("    {")
    A("        // ---- window / document state (assigned in Init, never inline) ----")
    A("        string title;")
    A("        bool   dirty;")
    A("        int    focus;")
    A("        int    scroll;")
    A("        int    activeTab;")
    A("")
    A("        // TODO(multi-window): one CLR slot per window already isolates")
    A("        // statics, but if this app ever shares a slot it MUST keep a")
    A("        // fixed-size Doc[] indexed by `id` (linear search, no Dictionary).")
    A("")
    A("        public %sApp()" % key)
    A("        {")
    A("            title = %s;" % cs(title))
    A("            dirty = false;")
    A("            focus = 0;")
    A("            scroll = 0;")
    A("            activeTab = 0;")
    A("        }")
    A("")
    A("        // ---- layout hit regions (from specs.json) ---------------------")
    for c in layout:
        n = ident(c.get("id", "c"))
        A("        const int X_%s = %d, Y_%s = %d, W_%s = %d, H_%s = %d;"
          % (n, c["x"], n, c["y"], n, c["w"], n, c["h"]))
    A("")
    A("        static bool InRect(int x, int y, int rx, int ry, int rw, int rh)")
    A("        {")
    A("            return x >= rx && x < rx + rw && y >= ry && y < ry + rh;")
    A("        }")
    A("")
    A("        public void OnPaint(int id, int w, int h)")
    A("        {")
    A("            // Only draw here.  Do NOT create objects that must survive")
    A("            // the frame: the bump heap is rewound after every Paint.")
    A("            // Client size is w x h; the constants above are prototype")
    A("            // coordinates and should be re-derived from w/h when the")
    A("            // kernel starts honouring per-app window sizes.")
    for c in layout:
        n = ident(c.get("id", "c"))
        label = c.get("text", "")
        if c["t"] in ("button",):
            A("            W.Button(X_%s, Y_%s, W_%s, H_%s, %s);"
              % (n, n, n, n, cs(label)))
        else:
            A("            W.Label(X_%s, Y_%s, %s);  // TODO: draw %s"
              % (n, n, cs(label), c["t"]))
    A("            // TODO: scrollbars, selection highlight, dirty marker,")
    A("            //       and any state-dependent greying-out of controls.")
    A("        }")
    A("")
    A("        public int OnClick(int id, int x, int y)")
    A("        {")
    A("            // Return non-zero when the click is consumed by the app.")
    A("            // Coordinates are client-relative (mforms subtracts ox/oy).")
    for c in layout:
        if c["t"] not in CLICKABLE:
            continue
        n = ident(c.get("id", "c"))
        A("            if (InRect(x, y, X_%s, Y_%s, W_%s, H_%s))" % (n, n, n, n))
        A("            {")
        A("                // TODO: %s -> %s" % (c["t"], c.get("text", "")))
        if c["t"] in ("tabs", "toolbar", "list", "grid"):
            A("                activeTab = 0;  // TODO: derive from x/y")
        A("                dirty = true;")
        A("                return 1;")
        A("            }")
    A("            return 0;")
    A("        }")
    A("")
    A("        public int OnKey(int id, int ch)")
    A("        {")
    A("            // Return non-zero when consumed (Tab MUST be consumed so the")
    A("            // window manager does not move focus away).")
    A("            // TODO: obtain the authoritative key code table from")
    A("            // mforms_key -> gui_legacy.cpp before implementing these:")
    for k, act in app["keys"].items():
        A("            //   %-12s -> %s" % (k, act))
    A("            if (ch == 9) return 1;   // Tab placeholder")
    A("            return 0;")
    A("        }")
    A("")
    A("        public string GetTitle(int id)")
    A("        {")
    A("            // TODO: append the document name and a (saved) hint with")
    A("            // U.Cat -- never use string '+'.  clr_heap_mark/reset wraps")
    A("            // this call in mforms_title(), so the string is temporary.")
    A("            return title;")
    A("        }")
    A("    }")
    A("}")
    A("")
    return "\n".join(out)


def main():
    os.makedirs(HTML_DIR, exist_ok=True)
    os.makedirs(MEX_DIR, exist_ok=True)

    buf = io.StringIO()
    json.dump(SPEC_DATA["_meta"], buf, ensure_ascii=False, indent=2)
    meta_js = buf.getvalue()
    buf = io.StringIO()
    json.dump(APPS, buf, ensure_ascii=False, indent=2)
    apps_js = buf.getvalue()
    data_js = ("window.NEX_META = " + meta_js + ";\n"
               "window.NEX_APPS = " + apps_js + ";")

    with open(os.path.join(HTML_DIR, "apps.js"), "w", encoding="utf-8") as fh:
        fh.write("// GENERATED by prototypes/gen.py -- edit prototypes/specs.json instead.\n")
        fh.write(data_js + "\n")

    # Keep a self-contained index.html too: some preview panels sandbox the
    # page and would refuse a relative <script src>.  The data block between
    # the two markers is regenerated on every run.
    hp = os.path.join(HTML_DIR, "index.html")
    if os.path.exists(hp):
        with open(hp, "r", encoding="utf-8") as fh:
            html = fh.read()
        s = html.find("<!-- NEX_DATA_START -->")
        e = html.find("<!-- NEX_DATA_END -->")
        if s >= 0 and e > s:
            block = ("<!-- NEX_DATA_START -->\n<script id=\"nex-data\">\n"
                     "/* GENERATED by prototypes/gen.py -- edit prototypes/specs.json instead */\n"
                     + data_js + "\n</script>\n")
            html = html[:s] + block + html[e:]
            with open(hp, "w", encoding="utf-8") as fh:
                fh.write(html)

    for app in APPS:
        d = os.path.join(MEX_DIR, app["key"])
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "Program.cs"), "w", encoding="utf-8") as fh:
            fh.write(render_cs(app))

    print("generated: html/apps.js + %d mex skeletons" % len(APPS))


if __name__ == "__main__":
    main()
