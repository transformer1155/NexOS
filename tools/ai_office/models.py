#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""可插拔模型后端 (pluggable model backends)。

每个后端实现两个方法:
    generate(system, user) -> str   生成带 `[NNN]` 行号前缀的协议源码文本。
    fix_line(protocol, num, ctx) -> str  只重写出错的那一行, 返回带前缀的单行。

内置后端:
    - MockBackend     离线、确定性, 供 self-test 与演示用 (无需任何网络/密钥)。
    - OpenAIBackend  OpenAI 兼容端点 (DeepSeek V4.1 Flash / Chat 等都走这里)。
    - MCPBackend     通过 MCP (stdio JSON-RPC) 把生成/修复委托给一个模型类 MCP 服务。

选型由环境变量决定 (见 get_backend):
    AIO_BACKEND   mock | openai | mcp   (默认 mock)
    AIO_MODEL     模型 id, 例如 deepseek-chat / deepseek-v4.1-flash
    AIO_BASE_URL  OpenAI 兼容 base url, 例如 https://api.deepseek.com/v1
    AIO_API_KEY   API key
    AIO_MCP_CMD   MCP 后端启动时执行的命令 (默认 "python -m ai_office.mcp_server")
"""
import abc
import json
import os
import subprocess
import sys
import time
import urllib.request

# ---------------------------------------------------------------------------
# 行号寻址协议: 给模型的系统提示词 (两用: 生成 / 单行修复)
# ---------------------------------------------------------------------------
PROTOCOL_RULES = (
    "你生成 Python 代码时必须遵守【行号寻址协议】: "
    "每一行源码前加 `[NNN]`, NNN 是从 001 开始的 3 位零填充十进制行号, "
    "行号连续递增。例如:\n"
    "[001] import sys\n"
    "[002] def add(a, b):\n"
    "[003]     return a + b\n"
    "[004] print(add(1, 2))\n"
    "只输出带行号的代码本身, 不要 ``` 代码块围栏, 不要任何解释文字。"
)

FIX_RULES = (
    "只重写指定的那一行。按行号寻址协议返回【单行】, 形如 `[003] 修正后的完整行`, "
    "保持该行应有的缩进。不要输出代码块围栏, 不要任何解释。"
)


class ModelBackend(abc.ABC):
    """模型后端的抽象接口。"""

    id = "abstract"

    @abc.abstractmethod
    def generate(self, system: str, user: str) -> str:
        """返回带 `[NNN]` 前缀的协议源码文本。"""

    @abc.abstractmethod
    def fix_line(self, protocol: str, num: int, error_context: str) -> str:
        """返回带前缀的【单行】修正文本 (含 `[NNN]`)。"""


# ---------------------------------------------------------------------------
# Mock 后端: 确定性, 离线可跑, 并能演示"故意留 bug + 单行修复"
# ---------------------------------------------------------------------------
class MockBackend(ModelBackend):
    """离线确定性后端。

    行为可控, 适合 self-test:
      - 默认生成一段"处理 Excel"的占位脚本 (每行都带行号)。
      - 若 user 含标记 `__BUG_AT_3__`, 则在第 3 行故意写错 (模拟首次生成的 bug),
        以便演示 debug 循环只重写那一行。
      - fix_line 收到第 3 行的修复请求时, 返回正确行。
    """

    id = "mock"

    def __init__(self, bug_line3: bool = False):
        self._bug_line3 = bug_line3

    def generate(self, system: str, user: str) -> str:
        bug = self._bug_line3 or ("__BUG_AT_3__" in user)
        # 故意留一个会抛 NameError 的 bug, 以便演示"报错 -> 单行修复"闭环。
        line3 = "[003]     return a + b + c  # c 未定义" if bug else "[003]     return a + b"
        # 生成一段较"长"的脚本 (约 18 行), 这样行号寻址时"上下文 ±2 行"只占
        # 全文的一小部分, Token 节省效果可量化 (演示用, 逻辑上只有 add 是必要的)。
        head = [
            "[001] # auto-generated by ai_office mock backend",
            "[002] def add(a, b):",
            line3,
            "[004]     # 以下为占位/样板行, 仅用于拉高脚本长度",
        ]
        filler = ["[0%02d]     pass  # padding line %d" % (i, i) for i in range(5, 15)]
        tail = [
            "[015] if __name__ == '__main__':",
            "[016]     for x in range(3):",
            "[017]         print('result =', add(x, x + 1))",
            "[018]     print('done')",
        ]
        return "\n".join(head + filler + tail)

    def fix_line(self, protocol: str, num: int, error_context: str) -> str:
        if num == 3:
            return "[003]     return a + b"
        # 通用兜底: 把出错行改成 pass
        import re
        m = re.match(r"^\s*\[(\d+)\]", protocol.splitlines()[0] if protocol else "")
        w = len(m.group(1)) if m else 3
        return "[%0*d]     pass  # auto-fixed" % (w, num)


# ---------------------------------------------------------------------------
# OpenAI 兼容后端 (DeepSeek 等)
# ---------------------------------------------------------------------------
class OpenAIBackend(ModelBackend):
    """调用 OpenAI 兼容的 /v1/chat/completions。

    可通过 AIO_BASE_URL / AIO_MODEL / AIO_API_KEY 配置; 默认指向 DeepSeek。
    """

    id = "openai"

    def __init__(self, base_url: str = "", model: str = "", api_key: str = ""):
        self.base_url = (base_url or os.environ.get("AIO_BASE_URL")
                         or "https://api.deepseek.com/v1").rstrip("/")
        self.model = model or os.environ.get("AIO_MODEL") or "deepseek-flash"
        self.api_key = api_key or os.environ.get("AIO_API_KEY") or ""

    def _chat(self, system: str, user: str, max_tokens: int = 1024) -> str:
        url = self.base_url + "/chat/completions"
        body = json.dumps({
            "model": self.model,
            "messages": [
                {"role": "system", "content": system},
                {"role": "user", "content": user},
            ],
            "stream": False,
            "max_tokens": max_tokens,
            "temperature": 0.2,
        }).encode("utf-8")
        req = urllib.request.Request(
            url, data=body,
            headers={
                "Content-Type": "application/json",
                "Authorization": "Bearer %s" % self.api_key,
            },
        )
        with urllib.request.urlopen(req, timeout=300) as r:
            data = json.load(r)
        return data["choices"][0]["message"]["content"].strip()

    def generate(self, system: str, user: str) -> str:
        return self._chat(PROTOCOL_RULES + "\n\n" + system, user)

    def fix_line(self, protocol: str, num: int, error_context: str) -> str:
        user = (
            "下面是带行号的脚本。第 [%03d] 行报错:\n%s\n\n"
            "报错信息:\n%s\n\n请按规则只重写第 [%03d] 行。"
            % (num, protocol, error_context, num)
        )
        return self._chat(FIX_RULES, user, max_tokens=256)


# ---------------------------------------------------------------------------
# MCP 后端: 通过 stdio JSON-RPC 把生成/修复委托给一个模型类 MCP 服务
# ---------------------------------------------------------------------------
class MCPBackend(ModelBackend):
    """把一次生成/修复当作一次 MCP `tools/call`。

    默认启动内置的 `mcp_server` (它本身走 env 选中的模型后端), 从而:
        ai_office 的 MCP server (对外暴露 generate/run/debug)
            └─ 每个 worker 调用 MCPBackend
                └─ 拉起一个 MCP 子进程, 发 tools/call 到模型类工具
    形成一个"通过 MCP 让模型并行生成脚本"的闭环。也可以指向任意实现了
    'ai_generate' / 'ai_fix_line' 工具的 MCP server (用 AIO_MCP_CMD 指定)。
    """

    id = "mcp"

    def __init__(self, cmd: "str | None" = None):
        self.cmd = cmd or os.environ.get("AIO_MCP_CMD") or (
            "%s -m ai_office.mcp_server" % (sys.executable or "python")
        )

    def _call(self, tool: str, arguments: dict) -> str:
        # 启动 MCP server (stdio), 完成 initialize 后调用 tools/call。
        proc = subprocess.Popen(
            self.cmd, shell=True,
            stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL, text=True,
            bufsize=1,
        )
        try:
            def send(obj):
                proc.stdin.write(json.dumps(obj) + "\n")
                proc.stdin.flush()

            send({"jsonrpc": "2.0", "id": 1, "method": "initialize",
                  "params": {"protocolVersion": "2024-11-05",
                             "capabilities": {}, "clientInfo": {"name": "ai_office", "version": "1.0"}}})
            # 读取直到 initialize 响应
            init = self._read_msg(proc)
            send({"jsonrpc": "2.0", "method": "notifications/initialized", "params": {}})
            send({"jsonrpc": "2.0", "id": 2, "method": "tools/call",
                  "params": {"name": tool, "arguments": arguments}})
            resp = self._read_msg(proc)
            if resp and "result" in resp:
                for c in resp["result"].get("content", []):
                    if c.get("type") == "text":
                        return c["text"].strip()
            return ""
        finally:
            try:
                proc.stdin.close()
            except Exception:
                pass
            try:
                proc.kill()
            except Exception:
                pass

    @staticmethod
    def _read_msg(proc) -> "dict | None":
        deadline = time.time() + 60
        buf = ""
        while time.time() < deadline:
            line = proc.stdout.readline()
            if not line:
                break
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
            except json.JSONDecodeError:
                buf = line
                continue
            if obj.get("id") in (1, 2) or obj.get("method") == "tools/call":
                return obj
        return None

    def generate(self, system: str, user: str) -> str:
        return self._call("ai_generate", {"system": system, "user": user})

    def fix_line(self, protocol: str, num: int, error_context: str) -> str:
        return self._call("ai_fix_line",
                          {"protocol": protocol, "num": num, "error_context": error_context})


# ---------------------------------------------------------------------------
# 后端工厂
# ---------------------------------------------------------------------------
def get_backend(name: "str | None" = None, **kw) -> ModelBackend:
    name = (name or os.environ.get("AIO_BACKEND") or "mock").lower()
    if name == "mock":
        return MockBackend(**kw)
    if name == "openai":
        return OpenAIBackend(**kw)
    if name == "mcp":
        return MCPBackend(**kw)
    raise ValueError("未知后端: %r (可选 mock/openai/mcp)" % name)
