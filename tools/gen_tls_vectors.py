#!/usr/bin/env python3
"""Generate authoritative ChaCha20-Poly1305 vectors with OpenSSL-backed
cryptography, for differential testing of the NexOS C implementation.

Writes tls_vectors.inc: a C array of test cases.
"""
import os, sys
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305

random = os.urandom

def hexs(b): return "".join("%02x" % x for x in b)

cases = []

# A few fixed cases (deterministic, reproducible)
fixed = [
    (bytes(range(0x80, 0xa0)), bytes.fromhex("070000004041424344454647"),
     bytes.fromhex("50515253c0c1c2c3c4c5c6c7"),
     b"Ladies and Gentlemen of the class of '99: If I could offer you only one "
     b"tip for the future, sunscreen would be it."),
    (bytes(32), bytes(12), b"", b""),
    (b"\x01" * 32, b"\x02" * 12, b"aad", b""),
    (b"\xff" * 32, b"\xff" * 12, b"", b"x"),
]
cases.extend(fixed)

# Randomized cases covering: empty/short/16-byte-aligned/long, with/without AAD
for i in range(24):
    klen = 32
    key = random(klen)
    nonce = random(12)
    aadlen = [0, 1, 7, 16, 17, 32, 100][i % 7]
    aad = random(aadlen)
    ptlen = [0, 1, 15, 16, 17, 31, 64, 129, 300][i % 9]
    pt = random(ptlen)
    cases.append((key, nonce, aad, pt))

out = []
out.append("// AUTO-GENERATED by tools/gen_tls_vectors.py -- DO NOT EDIT.")
out.append("// Authoritative AEAD_CHACHA20_POLY1305 vectors produced by OpenSSL")
out.append("// (via python-cryptography).  Regenerate with:")
out.append("//   python3 tools/gen_tls_vectors.py > tls_vectors.inc")
out.append("")
out.append("typedef struct {")
out.append("    const char* key;     /* 32 bytes hex */")
out.append("    const char* nonce;   /* 12 bytes hex */")
out.append("    const char* aad;     /* hex, may be \"\" */")
out.append("    const char* plain;   /* hex, may be \"\" */")
out.append("    const char* sealed;  /* hex: ciphertext || 16-byte tag */")
out.append("} aead_vector;")
out.append("")
out.append("static const aead_vector AEAD_VECTORS[] = {")
n = 0
for key, nonce, aad, pt in cases:
    aead = ChaCha20Poly1305(key)
    sealed = aead.encrypt(nonce, pt, aad)
    out.append('    { "%s", "%s", "%s", "%s",' % (hexs(key), hexs(nonce), hexs(aad), hexs(pt)))
    out.append('      "%s" },' % hexs(sealed))
    n += 1
out.append("};")
out.append("#define AEAD_VECTOR_COUNT %d" % n)
out.append("")
print("\n".join(out))
sys.stderr.write("generated %d vectors\n" % n)
