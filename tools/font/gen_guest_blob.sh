#!/bin/bash
# tools/font/gen_guest_blob.sh - assemble the minimal guest and emit it as a C header.
#
# The built-in VMM needs the guest program as a flat byte array it can copy
# into guest RAM.  Keeping the source in NASM (plugins/guest_smoke.asm) is far
# safer than hand-writing opcodes, so this script assembles it and generates
# plugins/guest_blob.h.
set -euo pipefail
cd "$(dirname "$0")/../.." || exit 1   # tools/font/ -> repo root

ASM=plugins/guest_smoke.asm
OUT=plugins/guest_blob.h
BIN=$(mktemp)
trap 'rm -f "$BIN"' EXIT

command -v nasm >/dev/null || { echo "error: nasm not installed" >&2; exit 1; }
nasm -f bin "$ASM" -o "$BIN"

{
    echo "/* guest_blob.h - GENERATED by tools/font/gen_guest_blob.sh -- do not edit."
    echo " *"
    echo " * Minimal guest program run by the built-in VMM (vmm.cpp).  It paints the"
    echo " * shared framebuffer, writes \"ready\" to the emulated UART, then does an"
    echo " * OUT to the exit port to trap back to the hypervisor."
    echo " *"
    echo " * Source: plugins/guest_smoke.asm"
    echo " */"
    echo "#ifndef GUEST_BLOB_H"
    echo "#define GUEST_BLOB_H"
    echo
    echo "#include <stdint.h>"
    echo
    echo "#define GUEST_CODE_PHYS   0x00001000u"
    echo "#define GUEST_FB_PHYS     0x00100000u"
    echo "#define GUEST_UART_PORT   0x03F8u"
    echo "#define GUEST_EXIT_PORT   0x0F00u"
    echo "#define GUEST_FB_W        1024u"
    echo "#define GUEST_FB_H        768u"
    echo
    echo "static const uint8_t guest_blob[] = {"
    od -An -v -tu1 "$BIN" | awk '
        { for (i = 1; i <= NF; i++) { printf "%s,", $i; n++;
            if (n % 12 == 0) printf "\n    "; else printf " "; } }
        END { printf "\n" }'
    echo "};"
    echo
    echo "#define GUEST_BLOB_LEN ((int)sizeof(guest_blob))"
    echo
    echo "#endif /* GUEST_BLOB_H */"
} > "$OUT"

echo "generated $OUT from $ASM ($(wc -c < "$BIN") bytes)"
