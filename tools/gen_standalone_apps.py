#!/usr/bin/env python3
# =====================================================================
#  gen_standalone_apps.py
# ---------------------------------------------------------------------
#  Turn every built-in application into an INDEPENDENT .mex assembly.
#
#  The old layout compiled 19 App classes into shell.mex.  This generator
#  creates one tiny C# project per application.  Each project links only
#  the freestanding toolkit (NexOS.Core / NexOS.Forms / Anim), the shared
#  compatibility shim, ONE application source file, and a generated
#  App.Main entry point implementing the same contract mforms.cpp uses
#  for standalone windows (Init / Paint / Click / Key / Title).
#
#  It also emits tools/standalone_apps.mk so make can rebuild every .mex.
#
#  Run from the repository root:  python tools/gen_standalone_apps.py
# =====================================================================
import os
import io

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHELL = "csharp/apps/Shell"
STAND = "csharp/apps/standalone"

# (mex basename, app source relative to repo root, App subclass, own Main.cs?)
# Notepad.mex is deliberately absent: it is already a real standalone app
# built by its own Makefile rule and is the reference implementation.
#
# The seven applications that used to live in Apps.cs now point at the
# PER-CLASS files produced by tools/split_app_sources.py.  Compiling the
# whole Apps.cs into every image would put seven copies of the same code
# in the SFS volume, which only has ~430 KB of headroom.
APPS = [
    ("ControlPanel", f"{STAND}/parts/ControlPanelApp.cs", "ControlPanelApp", False),
    ("FileExplorer", f"{STAND}/parts/FileExplorerApp.cs", "FileExplorerApp", False),
    ("TaskManager",  f"{STAND}/parts/TaskManagerApp.cs",  "TaskManagerApp",  False),
    ("Terminal",     f"{SHELL}/TerminalApp.cs",      "TerminalApp",     False),
    ("Calculator",   f"{STAND}/parts/CalculatorApp.cs",   "CalculatorApp",   False),
    ("About",        f"{STAND}/parts/AboutApp.cs",        "AboutApp",        False),
    ("MemOptimizer", f"{STAND}/parts/MemOptimizerApp.cs", "MemOptimizerApp", False),
    ("Browser",      f"{SHELL}/Browser.cs",          "BrowserApp",      False),
    ("AiSetup",      f"{SHELL}/AiSetup.cs",          "AiSetupApp",      False),
    ("AiAgent",      f"{SHELL}/AiAgent.cs",          "AiAgentApp",      False),
    ("Demo",         f"{SHELL}/Demo.cs",             "DemoApp",         False),
    ("NetTools",     f"{SHELL}/NetTools.cs",         "NetToolsApp",     False),
    ("AiLauncher",   f"{SHELL}/AiLauncher.cs",       "AiLauncherApp",   False),
    ("NetDefense",   f"{SHELL}/NetDefenseApp.cs",    "NetDefenseApp",   False),
    ("WebView",      f"{SHELL}/WebView.cs",          "WebViewApp",      False),
    ("VideoPlayer",  f"{STAND}/parts/VideoPlayerApp.cs",  "VideoPlayerApp",  False),
    ("AudioPlayer",  f"{STAND}/parts/AudioPlayerApp.cs",  "AudioPlayerApp",  False),
    ("AiChat",       f"{SHELL}/AiChat.cs",           "AiChatApp",       False),
    ("AiWorkbench",  f"{STAND}/parts/AiWorkbenchApp.cs", "AiWorkbenchApp", False),
    # BugReport ships its own Program.cs with a hand-written App.Main.
    ("BugReport",    f"{STAND}/BugReport/Program.cs", "BugReportApp",    True),
]

# Shared helper files that must be linked in with a given application.
# The Media header-probing helper is used by both media players.
EXTRA_SOURCES = {
    "VideoPlayer": [f"{STAND}/parts/_Shared_MediaPlayers.cs"],
    "AudioPlayer": [f"{STAND}/parts/_Shared_MediaPlayers.cs"],
}

CORE = [
    "../../../NexOS.Core/Corelib.cs",
    "../../../NexOS.Core/Sys.cs",
    "../../../NexOS.Core/SystemAlgo.cs",
    "../../../NexOS.Forms/Forms.cs",
    "../../../NexOS.Forms/Anim.cs",
    "../Shared/Shim.cs",
]

CSPROJ = """<Project Sdk="Microsoft.NET.Sdk">
  <!-- GENERATED by tools/gen_standalone_apps.py. Do not edit by hand. -->
  <PropertyGroup>
    <TargetFramework>netstandard2.0</TargetFramework>
    <OutputType>Library</OutputType>
    <AssemblyName>{name}</AssemblyName>
    <RootNamespace>App</RootNamespace>
    <NoStdLib>true</NoStdLib>
    <DisableImplicitFrameworkReferences>true</DisableImplicitFrameworkReferences>
    <RuntimeMetadataVersion>v4.0.30319</RuntimeMetadataVersion>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
    <GenerateAssemblyInfo>false</GenerateAssemblyInfo>
    <GenerateDocumentationFile>false</GenerateDocumentationFile>
    <GenerateTargetFrameworkAttribute>false</GenerateTargetFrameworkAttribute>
    <ProduceReferenceAssembly>false</ProduceReferenceAssembly>
    <AppendTargetFrameworkToOutputPath>false</AppendTargetFrameworkToOutputPath>
    <DebugType>none</DebugType>
    <Optimize>true</Optimize>
    <Deterministic>true</Deterministic>
    <NoWarn>CS0626;CS0649;CS8021;CS1591;CS0169;CS0414;CS0108</NoWarn>
    <DefineConstants>$(DefineConstants);STANDALONE_APP</DefineConstants>
  </PropertyGroup>
  <ItemGroup>
{compiles}  </ItemGroup>
</Project>
"""

MAIN_CS = """// GENERATED by tools/gen_standalone_apps.py -- do not edit by hand.
// Standalone entry contract, see mforms.cpp::slot_symbol().
using NexOS.Forms;

namespace App
{{
    public static class Main
    {{
        static NexOS.Forms.App app;

        public static void Init()
        {{
            if (app == null)
            {{
                app = new NexOS.Forms.{cls}();
                app.id = 0;
                app.KindId = {kind};
            }}
            // W.* controls register their hit rects on App.Current.  The
            // desktop shell normally sets this before Paint; a standalone
            // slot has to do it itself.
            NexOS.Forms.App.Current = app;
            // Anim's tween pool must live in the PERSISTENT part of this
            // slot's managed heap: Paint() rewinds the frame heap.
            NexOS.Forms.Anim.Init();
        }}

        public static int Paint(int id, int w, int h)
        {{
            Init();
            app.id = id;
            app.OnPaint();
            return 0;
        }}

        public static int Click(int id, int x, int y)
        {{
            Init();
            app.id = id;
            app.OnClick(x, y);
            return 0;
        }}

        public static int Key(int id, int ch)
        {{
            Init();
            app.id = id;
            app.OnKey(ch);
            return 0;
        }}

        public static string Title(int id)
        {{
            Init();
            app.id = id;
            return app.GetTitle();
        }}
    }}
}}
"""

# kind id per mex, taken from sfs_files/apps.man (keep in sync)
KIND_OF = {
    "ControlPanel": 0, "FileExplorer": 1, "TaskManager": 2, "Terminal": 3,
    "Calculator": 4, "About": 5, "MemOptimizer": 6, "Browser": 8,
    "AiSetup": 9, "AiAgent": 10, "Demo": 11, "NetTools": 12,
    "AiLauncher": 13, "NetDefense": 14, "WebView": 15, "VideoPlayer": 16,
    "AudioPlayer": 17, "AiChat": 18, "BugReport": 19, "AiWorkbench": 20,
}

RULE = """
$(SFS_DIR)/{name}.mex: {deps}
\t@set -e; \\
\tif command -v dotnet >/dev/null 2>&1; then DN=dotnet; \\
\telif command -v dotnet.exe >/dev/null 2>&1; then DN=dotnet.exe; \\
\telse echo "!! .NET SDK not found - cannot build standalone app $@"; exit 1; fi; \\
\t"$$DN" build {proj} -c Release -v quiet --nologo && \\
\t"$(PYTHON)" tools/mex_pack.py {dll} $@ "App.Main::Init" && \\
\techo "==> standalone app: $@ ($$(stat -c%s $@) bytes)"
"""


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with io.open(full, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    mex_list = []
    rules = []
    for name, src, cls, own_main in APPS:
        d = f"{STAND}/{name}"
        compiles = "".join(f'    <Compile Include="{c}" />\n' for c in CORE)
        # application source: from csharp/apps/standalone/<Name>/ up three is
        # csharp/, so ../../Shell/<file> or ../../standalone/... is correct
        rel_src = "../../" + os.path.relpath(src, "csharp/apps").replace(os.sep, "/")
        extra_deps = []
        if not own_main:
            compiles += f'    <Compile Include="{rel_src}" />\n'
        # Shared helper files (e.g. the media header prober used by both
        # media players).  Each application links only what it actually
        # uses, so no image carries another application's code.
        for extra in EXTRA_SOURCES.get(name, []):
            rel_extra = "../../" + os.path.relpath(extra, "csharp/apps").replace(os.sep, "/")
            compiles += f'    <Compile Include="{rel_extra}" />\n'
            extra_deps.append(extra)
        compiles += '    <Compile Include="Main.cs" />\n' if not own_main \
                    else '    <Compile Include="Program.cs" />\n'

        write(f"{d}/App.csproj", CSPROJ.format(name=name, compiles=compiles))
        if not own_main:
            write(f"{d}/Main.cs", MAIN_CS.format(cls=cls, kind=KIND_OF[name]))

        proj = f"{d}/App.csproj"
        dll = f"{d}/bin/Release/{name}.dll"
        main_src = f"{d}/Program.cs" if own_main else f"{d}/Main.cs"
        deps = " ".join([
            proj, main_src, src, f"{STAND}/Shared/Shim.cs",
            "csharp/NexOS.Core/Corelib.cs", "csharp/NexOS.Core/Sys.cs",
            "csharp/NexOS.Core/SystemAlgo.cs",
            "csharp/NexOS.Forms/Forms.cs", "csharp/NexOS.Forms/Anim.cs",
            "tools/mex_pack.py",
        ] + extra_deps)
        rules.append(RULE.format(name=name, deps=deps, proj=proj, dll=dll))
        mex_list.append(name + ".mex")

    mk = [
        "# GENERATED by tools/gen_standalone_apps.py -- do not edit by hand.",
        "# Included near the top of Makefile so $(SFS_IMG) can depend on",
        "# every standalone image before its rule is parsed.",
        "STANDALONE_MEX := " + " ".join("$(SFS_DIR)/" + m for m in mex_list),
        "",
    ]
    mk.extend(rules)
    write("tools/standalone_apps.mk", "\n".join(mk))
    print(f"generated {len(APPS)} standalone projects, {len(mex_list)} mex images")


if __name__ == "__main__":
    main()
